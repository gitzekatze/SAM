//! Build synthetic Type 2 AppImages for tests, CI and demos.
//!
//! The "runtime" is a copy of a host ELF with the `AI\x02` magic set (it is
//! not executable as an AppImage), followed by a real SquashFS payload
//! written with backhand. SAM never executes the runtime, so this is
//! enough to exercise intake, detection and launching.

use std::io::Cursor;
use std::path::Path;

use anyhow::{anyhow, Context, Result};
use backhand::compression::{CompressionOptions, Compressor, Lz4};
use backhand::{FilesystemCompressor, FilesystemWriter, NodeHeader};

