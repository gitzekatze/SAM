#!/usr/bin/env python3
"""Writes docs/test-library.md: every automated test of SAM, what it proves,
and where it lives, grouped by the part of SAM it tests.

    scripts/test-library.py          write the catalog
    scripts/test-library.py --check  fail when the catalog is out of date

A test's promise is the first sentence of its doc comment (`///` above
`#[test]`); without one, its name is read as a sentence
(`stop_closes_running_apps` → "Stop closes running apps"). Name tests after
the promise they keep, and say "Regression:" in the doc comment when a test
guards against a bug that happened.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "test-library.md"

# The parts of SAM (see docs/architecture.md, components).
PARTS = {
    "sam-core": "Permission model, risk, warnings, configuration and file formats",
    "sam-detect": "Recognizing AppImages and what they need (ELF, toolkits, signatures)",
    "sam-intake": "Unpacking AppImages safely, metadata, menu entries",
    "sam-profile": "Recommendations, the user's presets, change checks, permission tags",
    "sam-sandbox": "Building the Bubblewrap command from the permissions",
    "sam-runner": "Operations: add, launch, verify, repair, update, group changes; the sandbox at run time",
    "sam-storage": "App records, presets and logs on disk",
    "sam-jail-cli": "The command line and its JSON interface",
    "sam-gtk": "The window (logic that runs without a display)",
}

GUI_CHECKS = [
    ("tests/gui/smoke.sh", "Every page of the window opens without GTK warnings, criticals or panics, in a wide and a narrow window."),
    ("tests/gui/permissions-atspi.sh", "Through the accessibility interface: the Permissions page selects apps, names its controls, warns before an app loses something it needs, applies a group change, and Undo restores every app; tag filters cycle; the one-app editor shows the stored settings after a save that failed."),
    ("tests/gui/app-page-atspi.sh", "Through the accessibility interface: the app page has one Test button with a visible test state, the trash button as high as Test and Launch, advice in one group, a visible \"Files This App Saved\" row, and a remove dialog whose three choices are not preselected and whose button cannot be pressed before a choice; Confirm Settings for a record changed outside SAM names what the settings allow as they are when it is pressed, Cancel keeps the app blocked, and no \"Got It\" of an update's note confirms them before; a save that failed shows the stored settings; a finding of a failed start says it also starts the app."),
    ("tests/gui/flow-atspi.sh", "Through the accessibility interface: Create Sandbox and Launch from the window; in Preferences, turning Landlock off for every app asks first and Cancel keeps it on, and a save that failed leaves the switch where the setting is; the window in German and English."),
    ("tests/gui/a11y-atspi.sh", "Through the accessibility interface, on every page of the window: every visible, enabled control has a name a screen reader can say, and the keyboard reaches it."),
    ("tests/gui/taskbar-kwin.sh", "In a hidden KWin session, a sandboxed app's window is named after SAM's menu entry, so the taskbar shows the app's own icon and name."),
    ("crates/sam-runner/tests/fuzz.rs with SAM_FUZZ_ITERS=100000", "A long fuzzing session: hundreds of thousands of changed inputs for every parser of untrusted data, without a crash."),
    ("tests/real-apps/run.sh", "Real AppImages from the test sets start in their sandbox; results are compared with the last baseline."),
]


def sentence(name: str) -> str:
    words = name.replace("_", " ").strip()
    return words[:1].upper() + words[1:] + "."


def tests_in(path: pathlib.Path):
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        if line.strip() != "#[test]":
            continue
        # The function name follows (attributes such as #[ignore] may come between).
        name = None
        for j in range(i + 1, min(i + 6, len(lines))):
            m = re.search(r"\bfn\s+([a-z0-9_]+)", lines[j])
            if m:
                name = m.group(1)
                break
        if not name:
            continue
        doc = []
        k = i - 1
        while k >= 0 and lines[k].strip().startswith("///"):
            doc.insert(0, lines[k].strip()[3:].strip())
            k -= 1
        text = " ".join(doc).strip()
        promise = re.split(r"(?<=[.!?])\s", text)[0] if text else sentence(name)
        regression = "Regression" in text
        yield name, promise, i + 1, regression


def build() -> str:
    out = [
        "# Test library",
        "",
        "Every automated test of SAM, what it proves, and where it lives. A reviewer",
        "can pick any promise below and read or run the test that keeps it.",
        "Generated by `scripts/test-library.py`; CI fails when this file is out of date.",
        "",
        "Rules for changes (see CONTRIBUTING.md): every change comes with a test that",
        "proves it, and every fixed bug with a regression test that fails without the",
        "fix. Tests are named after the promise they keep. ⟲ marks regression tests.",
        "",
        "Run everything: `cargo test --workspace` (unit and integration tests),",
        "`tests/gui/smoke.sh OUTDIR`, `tests/gui/permissions-atspi.sh OUTDIR` and `tests/gui/taskbar-kwin.sh OUTDIR` (window).",
        "",
    ]
    total = 0
    for crate, what in PARTS.items():
        files = sorted((ROOT / "crates" / crate).rglob("*.rs"))
        rows = []
        for f in files:
            for name, promise, line, reg in tests_in(f):
                rel = f.relative_to(ROOT)
                rows.append(f"| {'⟲ ' if reg else ''}{promise} | [`{name}`]({'../' + str(rel)}#L{line}) |")
        if not rows:
            continue
        total += len(rows)
        out += [f"## {crate}: {what}", "", f"{len(rows)} tests.", "", "| Promise | Test |", "|---|---|", *rows, ""]
    out += ["## The window and real AppImages", "", "| Check | What it proves |", "|---|---|"]
    out += [f"| `{p}` | {t} |" for p, t in GUI_CHECKS]
    out += ["", f"Total: {total} automated Rust tests plus {len(GUI_CHECKS)} scripted checks.", ""]
    return "\n".join(out)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/test-library.md is out of date: run scripts/test-library.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
