#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.md: every library that is built into SAM's
programs (sam-jail and sam-jail-gui), with its license and the license
files its authors ship. Most of these licenses (MIT, Apache-2.0, BSD)
require their text and copyright notice to travel with the program, so
the AppImage and the packages install this file next to SAM's own
license.

    scripts/third-party-licenses.py           write the file
    scripts/third-party-licenses.py --check   fail when it is out of date

Only libraries the programs really contain count: normal dependencies of
the two binaries on x86_64 Linux, not tools used only for building or
testing. The list comes from `cargo metadata` and Cargo.lock, so it
changes exactly when the dependencies change.
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-LICENSES.md"
BINARIES = ("sam-jail-cli", "sam-gtk")
LICENSE_FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE", "AUTHORS")


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-unknown-linux-gnu"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(m):
    """Packages reachable from the binaries through normal dependencies."""
    packages = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    start = [p["id"] for p in m["packages"] if p["name"] in BINARIES]
    seen, stack = set(), list(start)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k.get("kind") is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    workspace = set(m["workspace_members"])
    return sorted((packages[p] for p in seen if p not in workspace), key=lambda p: (p["name"].lower(), p["version"]))


def license_texts(pkg):
    folder = pathlib.Path(pkg["manifest_path"]).parent
    files = sorted(f for f in folder.iterdir() if f.is_file() and f.name.upper().startswith(LICENSE_FILES))
    return [(f.name, f.read_text(errors="replace").strip()) for f in files]


def render(pkgs):
    lines = [
        "# Third-party licenses",
        "",
        "SAM's programs (`sam-jail` and `sam-jail-gui`) contain the libraries below,",
        "written by other people. SAM itself is licensed under GPL-3.0-or-later",
        "([LICENSE](LICENSE)); each library keeps its own license, listed here with",
        "the license files its authors ship.",
        "",
        "This file is generated by `scripts/third-party-licenses.py` from Cargo.lock.",
        "Libraries SAM uses from your system at run time (GTK, libadwaita,",
        "Bubblewrap and others) are not part of SAM's files and are not listed.",
        "",
        f"{len(pkgs)} libraries.",
        "",
        "| Library | Version | License |",
        "|---|---|---|",
    ]
    for p in pkgs:
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see below'} |")
    lines.append("")
    # A text that several libraries ship word for word (the Apache license,
    # mostly) is printed once at the end; each library points to it.
    counts = {}
    for p in pkgs:
        for _, text in license_texts(p):
            counts[text] = counts.get(text, 0) + 1
    shared = {t: f"shared text {i + 1}" for i, t in enumerate(t for t, n in counts.items() if n > 1)}
    for p in pkgs:
        lines += [f"## {p['name']} {p['version']}", "", f"License: {p.get('license') or p.get('license_file') or 'not stated'}"]
        if p.get("repository"):
            lines.append(f"Source: {p['repository']}")
        lines.append("")
        texts = license_texts(p)
        if not texts:
            lines += ["The crate ships no license file; its license is the one named above.", ""]
        for name, text in texts:
            if text in shared:
                lines += [f"### {name}", "", f"The text is printed once below, as {shared[text]}.", ""]
            else:
                lines += [f"### {name}", "", "```text", text, "```", ""]
    if shared:
        lines += ["## Shared license texts", ""]
        for text, label in shared.items():
            lines += [f"### {label.capitalize()}", "", "```text", text, "```", ""]
    return "\n".join(lines)


def main():
    text = render(shipped_packages(metadata()))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("THIRD-PARTY-LICENSES.md is out of date: run scripts/third-party-licenses.py")
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
